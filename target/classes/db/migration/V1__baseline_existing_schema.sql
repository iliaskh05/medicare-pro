-- Baseline of the 6 tables created historically by Hibernate ddl-auto=update.
-- Idempotent: existing databases skip CREATE TABLE; unique indexes/checks are IF NOT EXISTS.
-- Do not DROP columns. Legacy extras (patients.age, medecins_referents.imported_at) are kept.

CREATE TABLE IF NOT EXISTS patients (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_complet         VARCHAR(255),
    age                 INTEGER,
    cin                 VARCHAR(255),
    date_naissance      DATE,
    sexe                VARCHAR(1),
    telephone           VARCHAR(255),
    email               VARCHAR(255),
    mutuelle            VARCHAR(255),
    num_affiliation     VARCHAR(255),
    medecin_traitant    VARCHAR(255),
    ville               VARCHAR(255),
    quartier            VARCHAR(255),
    adresse             VARCHAR(255),
    prochain_rdv        TIMESTAMP(6)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_patients_cin ON patients (cin);

CREATE TABLE IF NOT EXISTS medecins_referents (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medecin_excel    VARCHAR(255),
    nom                 VARCHAR(255),
    telephone           VARCHAR(255),
    email               VARCHAR(255),
    specialite          VARCHAR(255),
    adresse             TEXT,
    ville               VARCHAR(255),
    quartier            VARCHAR(255),
    imported_at         TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS utilisateurs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_complet         VARCHAR(255) NOT NULL,
    email               VARCHAR(255) NOT NULL,
    mot_de_passe        VARCHAR(255) NOT NULL,
    role                VARCHAR(32)  NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_utilisateurs_email ON utilisateurs (email);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token               VARCHAR(64) NOT NULL,
    utilisateur_id      BIGINT NOT NULL REFERENCES utilisateurs (id),
    date_expiration     TIMESTAMP(6) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_password_reset_tokens_token ON password_reset_tokens (token);

CREATE TABLE IF NOT EXISTS examens (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_sejour          VARCHAR(255) NOT NULL,
    patient_id          BIGINT NOT NULL REFERENCES patients (id),
    prescripteur_id     BIGINT REFERENCES medecins_referents (id),
    prescripteur_nom    VARCHAR(255),
    medecin             VARCHAR(255),
    date_examen         TIMESTAMP(6) NOT NULL,
    salle               VARCHAR(255),
    description         VARCHAR(255),
    modalite            VARCHAR(255) NOT NULL,
    etat_patient        VARCHAR(255) NOT NULL,
    statut_cr           VARCHAR(255) NOT NULL,
    paiement            VARCHAR(255) NOT NULL,
    montant             NUMERIC(10, 2),
    compte_rendu        TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_examens_num_sejour ON examens (num_sejour);

CREATE TABLE IF NOT EXISTS historique_examen (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examen_id           BIGINT NOT NULL REFERENCES examens (id),
    date                TIMESTAMP(6),
    auteur              VARCHAR(255),
    action              VARCHAR(255)
);

-- Enum CHECKs matching Hibernate ddl-auto=update on the live database.
DO $$
BEGIN
    ALTER TABLE utilisateurs
        ADD CONSTRAINT utilisateurs_role_check
        CHECK (role IN ('DIRECTEUR', 'RADIOLOGUE', 'MANIPULATEUR', 'SECRETARIAT'));
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

