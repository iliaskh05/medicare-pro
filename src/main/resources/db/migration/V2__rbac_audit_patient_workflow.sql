-- RBAC, audit immuable, idempotence, colonnes métier sur patients/examens/utilisateurs.

-- ========== utilisateurs (soft lock, audit champs) ==========
ALTER TABLE utilisateurs
    ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS locked_until TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP(6);

-- ========== patients 360 ==========
ALTER TABLE patients
    ADD COLUMN IF NOT EXISTS nom VARCHAR(120),
    ADD COLUMN IF NOT EXISTS prenom VARCHAR(120),
    ADD COLUMN IF NOT EXISTS numero_dossier VARCHAR(32),
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS created_by_id BIGINT REFERENCES utilisateurs (id),
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS version INTEGER NOT NULL DEFAULT 0;

UPDATE patients
SET nom = COALESCE(nom, NULLIF(split_part(TRIM(nom_complet), ' ', 1), '')),
    prenom = COALESCE(
        prenom,
        NULLIF(TRIM(substring(TRIM(nom_complet) from length(split_part(TRIM(nom_complet), ' ', 1)) + 1)), '')
    )
WHERE nom_complet IS NOT NULL AND nom IS NULL;

UPDATE patients
SET numero_dossier = 'PAT-' || LPAD(id::text, 6, '0')
WHERE numero_dossier IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uk_patients_numero_dossier ON patients (numero_dossier);
CREATE INDEX IF NOT EXISTS idx_patients_cin ON patients (cin);
CREATE INDEX IF NOT EXISTS idx_patients_telephone ON patients (telephone);
CREATE INDEX IF NOT EXISTS idx_patients_nom_prenom ON patients (LOWER(nom), LOWER(prenom));
CREATE INDEX IF NOT EXISTS idx_patients_date_naissance ON patients (date_naissance);
CREATE INDEX IF NOT EXISTS idx_patients_num_affiliation ON patients (num_affiliation);
CREATE INDEX IF NOT EXISTS idx_patients_deleted_at ON patients (deleted_at);

-- ========== examens / workflow ==========
ALTER TABLE examens
    ADD COLUMN IF NOT EXISTS workflow_status VARCHAR(32) NOT NULL DEFAULT 'SCHEDULED',
    ADD COLUMN IF NOT EXISTS priorite VARCHAR(16) NOT NULL DEFAULT 'ROUTINE',
    ADD COLUMN IF NOT EXISTS exam_type_code VARCHAR(64),
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS created_by_id BIGINT REFERENCES utilisateurs (id),
    ADD COLUMN IF NOT EXISTS assigned_radiologue_id BIGINT REFERENCES utilisateurs (id),
    ADD COLUMN IF NOT EXISTS cancelled_at TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS version INTEGER NOT NULL DEFAULT 0;

UPDATE examens SET workflow_status = CASE etat_patient
    WHEN 'attendu' THEN 'SCHEDULED'
    WHEN 'arrive' THEN 'ARRIVED'
    WHEN 'retard' THEN 'WAITING'
    WHEN 'attente_longue' THEN 'WAITING'
    ELSE 'SCHEDULED'
END
WHERE workflow_status = 'SCHEDULED';

CREATE INDEX IF NOT EXISTS idx_examens_date ON examens (date_examen);
CREATE INDEX IF NOT EXISTS idx_examens_statut ON examens (etat_patient);
CREATE INDEX IF NOT EXISTS idx_examens_workflow ON examens (workflow_status);
CREATE INDEX IF NOT EXISTS idx_examens_modalite ON examens (modalite);
CREATE INDEX IF NOT EXISTS idx_examens_patient ON examens (patient_id);
CREATE INDEX IF NOT EXISTS idx_examens_prescripteur ON examens (prescripteur_id);
CREATE INDEX IF NOT EXISTS idx_examens_radiologue ON examens (assigned_radiologue_id);

CREATE TABLE IF NOT EXISTS exam_status_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examen_id           BIGINT NOT NULL REFERENCES examens (id),
    from_status         VARCHAR(32),
    to_status           VARCHAR(32) NOT NULL,
    actor_id            BIGINT REFERENCES utilisateurs (id),
    actor_name          VARCHAR(255),
    reason              VARCHAR(500),
    created_at          TIMESTAMP(6) NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_exam_status_history_examen ON exam_status_history (examen_id, created_at);

-- ========== RBAC ==========
CREATE TABLE IF NOT EXISTS roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32) NOT NULL UNIQUE,
    label       VARCHAR(80) NOT NULL,
    system_role BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL UNIQUE,
    label       VARCHAR(120) NOT NULL,
    domain      VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id         BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id   BIGINT NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id     BIGINT NOT NULL REFERENCES utilisateurs (id) ON DELETE CASCADE,
    role_id     BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

