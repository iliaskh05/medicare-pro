-- ========== audit immuable ==========
CREATE TABLE IF NOT EXISTS audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action          VARCHAR(64) NOT NULL,
    entity_type     VARCHAR(64),
    entity_id       VARCHAR(64),
    user_id         BIGINT,
    user_email      VARCHAR(255),
    ip_address      VARCHAR(64),
    correlation_id  VARCHAR(64),
    metadata        JSONB,
    before_state    JSONB,
    after_state     JSONB,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs (action, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user ON audit_logs (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS security_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type      VARCHAR(64) NOT NULL,
    email           VARCHAR(255),
    ip_address      VARCHAR(64),
    success         BOOLEAN NOT NULL,
    detail          VARCHAR(500),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_security_events_email ON security_events (email, created_at DESC);

CREATE OR REPLACE FUNCTION prevent_audit_mutation()
RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Les journaux d''audit sont immuables';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS audit_logs_no_update ON audit_logs;
CREATE TRIGGER audit_logs_no_update
    BEFORE UPDATE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

DROP TRIGGER IF EXISTS audit_logs_no_delete ON audit_logs;
CREATE TRIGGER audit_logs_no_delete
    BEFORE DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

DROP TRIGGER IF EXISTS security_events_no_update ON security_events;
CREATE TRIGGER security_events_no_update
    BEFORE UPDATE ON security_events
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

DROP TRIGGER IF EXISTS security_events_no_delete ON security_events;
CREATE TRIGGER security_events_no_delete
    BEFORE DELETE ON security_events
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

-- ========== idempotence ==========
CREATE TABLE IF NOT EXISTS idempotency_keys (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key     VARCHAR(128) NOT NULL,
    user_id             BIGINT,
    request_hash        VARCHAR(64) NOT NULL,
    response_status     INTEGER,
    response_body       TEXT,
    created_at          TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    expires_at          TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_idempotency_key_user UNIQUE (idempotency_key, user_id)
);

CREATE INDEX IF NOT EXISTS idx_idempotency_expires ON idempotency_keys (expires_at);
